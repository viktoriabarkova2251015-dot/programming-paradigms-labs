решение(Волк, Ниф, Наф, Нуф) :-
    Позиции = [0,1,2,3],
    permutation([ПВолка, ПНифа, ПНафа, ПНуфа], Позиции),
    Темы = [флора, спорт, космос],
    permutation([ТНифа, ТНафа, ТНуфа],Темы),
    слева(ПВолка, ПНафа),         
    (   ТНифа = космос -> ПКосмоса = ПНифа;
        ТНафа = космос -> ПКосмоса = ПНафа;
        ТНуфа = космос -> ПКосмоса = ПНуфа),
    справа(ПНифа, ПКосмоса), 
    напротив(ПНафа, ПНуфа), 
    ТНуфа \= спорт,

    Волк = фауна,
    Ниф = ТНифа,
    Наф = ТНафа,
    Нуф = ТНуфа.